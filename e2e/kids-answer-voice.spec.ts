import { expect, test } from '@playwright/test';
import { KIDS_SHOW_QUESTIONS } from '../src/shared/kids-show-questions';
import { professorAudio, trackProfessorAudio } from './professor-audio';
import { showKidsOperator } from './kids-operator';

test.use({viewport:{width:1280,height:800},isMobile:false});
test('Antworten: Smartphone und Desktop lesen alle drei gemischten Felder am Beamer vor',async({page,browser})=>{
  await trackProfessorAudio(page);await page.goto('/kids');
  await page.getByRole('button',{name:'Show vorbereiten',exact:false}).click();await showKidsOperator(page);
  await page.getByRole('button',{name:'Bedienung',exact:false}).click();
  await page.getByRole('button',{name:'Smartphone verbinden',exact:true}).click();
  const link=page.getByRole('link',{name:'Fernbedienung öffnen',exact:false});await expect(link).toBeVisible();
  const url=await link.getAttribute('href');
  await page.getByRole('button',{name:'Zur Partie',exact:true}).click();
  const context=await browser.newContext({viewport:{width:390,height:844},locale:'de-DE'}),remote=await context.newPage();
  const remoteAudio:string[]=[];remote.on('request',r=>{if(r.url().includes('/professor-bluff/'))remoteAudio.push(r.url());});
  await remote.goto(url!);
  await remote.getByRole('button',{name:'Mission starten',exact:true}).click();
  await remote.getByRole('button',{name:'Erste Aufgabe im Kapitel',exact:true}).click();
  await expect(page.locator('#kids-question')).toBeVisible();
  expect((await professorAudio(page)).starts).toBe(0);
  await expect(page.getByRole('button',{name:'Antworten vorlesen',exact:false})).toHaveCount(0);
  const answers=await page.locator('.kids-answer-text').allTextContents();
  const q=KIDS_SHOW_QUESTIONS[0],canonical=[q.answer,...q.distractors];
  const expected=answers.flatMap((a,field)=>[`answer-number-0-${field}`,`answer-0-${canonical.indexOf(a)}`]);
  await remote.getByRole('button',{name:'Antworten vorlesen',exact:false}).click();
  await expect.poll(async()=>(await professorAudio(page)).played,{timeout:20000}).toEqual(expected);
  await expect(page.locator('.kids-clock-left')).toHaveAttribute('aria-label','30 Sekunden');
  await remote.setViewportSize({width:1440,height:900});
  await remote.getByRole('button',{name:'Antworten vorlesen',exact:false}).click();
  await expect.poll(async()=>(await professorAudio(page)).starts).toBeGreaterThanOrEqual(7);
  await remote.getByRole('button',{name:'Professor-Audio stoppen',exact:false}).click();
  await expect.poll(async()=>(await professorAudio(page)).stops).toBeGreaterThan(0);
  const stopped=(await professorAudio(page)).starts;
  await page.waitForTimeout(1200);expect((await professorAudio(page)).starts).toBe(stopped);
  await remote.getByRole('button',{name:'Antworten vorlesen',exact:false}).click();
  await expect.poll(async()=>(await professorAudio(page)).starts).toBeGreaterThanOrEqual(stopped+1);
  await remote.getByRole('button',{name:'30 Sekunden starten',exact:true}).click();
  await expect.poll(async()=>(await professorAudio(page)).played.at(-1)).toBe('interjection-signal-go');
  await expect(remote.getByRole('button',{name:'Antworten vorlesen',exact:false})).toHaveCount(0);
  expect(remoteAudio).toEqual([]);
  await context.close();
});
